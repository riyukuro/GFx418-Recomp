{
    if (psc->GetBuiltin(ASBuiltin_length).CompareBuiltIn_CaseCheck(name, psc->IsCaseSensitive()))
    {
        if (!Object::GetMemberRaw(psc, name, val) || !val->IsSet())
            val->SetInt(sValue.GetLength());
        return true;
    }
    if (Object::GetMemberRaw(psc, name, val))
        return true;
    return false;
}

